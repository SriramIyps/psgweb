-- ─────────────────────────────────────────────
-- 5. ATOMIC RPC FUNCTION FOR SAVING RESEARCH DATA
-- ─────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.save_application_research(
    p_application_id BIGINT,
    p_publications JSONB DEFAULT '[]'::jsonb,
    p_patents JSONB DEFAULT '[]'::jsonb,
    p_consultancy JSONB DEFAULT '[]'::jsonb,
    p_projects JSONB DEFAULT '[]'::jsonb,
    p_iso_involvement BOOLEAN DEFAULT false,
    p_iso_details TEXT DEFAULT '',
    p_naac_iqac_details TEXT DEFAULT '',
    p_admin_positions JSONB DEFAULT '[]'::jsonb
)
RETURNS VOID AS $$
DECLARE
    pub_row JSONB;
    pat_row JSONB;
    con_row JSONB;
    prj_row JSONB;
    keep_pub_ids BIGINT[] := ARRAY[]::BIGINT[];
    keep_pat_ids BIGINT[] := ARRAY[]::BIGINT[];
    keep_con_ids BIGINT[] := ARRAY[]::BIGINT[];
    keep_prj_ids BIGINT[] := ARRAY[]::BIGINT[];
    row_id BIGINT;
BEGIN
    -- 1. Update parent application admin/quality fields
    UPDATE public.applications
    SET
        iso_involvement = p_iso_involvement,
        iso_details = p_iso_details,
        naac_iqac_details = p_naac_iqac_details,
        admin_positions_json = p_admin_positions::text
    WHERE id = p_application_id;

    -- 2. Upsert Publications
    FOR pub_row IN SELECT * FROM jsonb_array_elements(p_publications) LOOP
        row_id := (pub_row->>'id')::BIGINT;
        IF row_id IS NOT NULL AND row_id > 0 THEN
            UPDATE public.app_publications SET
                type = pub_row->>'type',
                scope = pub_row->>'scope',
                indexing_category = pub_row->>'indexing_category',
                title = pub_row->>'title',
                publisher_journal = pub_row->>'publisher_journal',
                isbn_issn = pub_row->>'isbn_issn',
                year = NULLIF(pub_row->>'year', '')::INTEGER,
                doi_link = pub_row->>'doi_link',
                additional_details = pub_row->>'additional_details'
            WHERE id = row_id AND application_id = p_application_id;
            keep_pub_ids := array_append(keep_pub_ids, row_id);
        ELSE
            INSERT INTO public.app_publications (
                application_id, type, scope, indexing_category, title,
                publisher_journal, isbn_issn, year, doi_link, additional_details
            ) VALUES (
                p_application_id,
                pub_row->>'type',
                pub_row->>'scope',
                pub_row->>'indexing_category',
                pub_row->>'title',
                pub_row->>'publisher_journal',
                pub_row->>'isbn_issn',
                NULLIF(pub_row->>'year', '')::INTEGER,
                pub_row->>'doi_link',
                pub_row->>'additional_details'
            ) RETURNING id INTO row_id;
            keep_pub_ids := array_append(keep_pub_ids, row_id);
        END IF;
    END LOOP;
    -- Delete removed publications
    DELETE FROM public.app_publications
    WHERE application_id = p_application_id AND NOT (id = ANY(keep_pub_ids));

    -- 3. Upsert Patents
    FOR pat_row IN SELECT * FROM jsonb_array_elements(p_patents) LOOP
        row_id := (pat_row->>'id')::BIGINT;
        IF row_id IS NOT NULL AND row_id > 0 THEN
            UPDATE public.app_patents SET
                title = pat_row->>'title',
                status = pat_row->>'status',
                patent_number = pat_row->>'patent_number',
                year = NULLIF(pat_row->>'year', '')::INTEGER,
                additional_details = pat_row->>'additional_details'
            WHERE id = row_id AND application_id = p_application_id;
            keep_pat_ids := array_append(keep_pat_ids, row_id);
        ELSE
            INSERT INTO public.app_patents (
                application_id, title, status, patent_number, year, additional_details
            ) VALUES (
                p_application_id,
                pat_row->>'title',
                pat_row->>'status',
                pat_row->>'patent_number',
                NULLIF(pat_row->>'year', '')::INTEGER,
                pat_row->>'additional_details'
            ) RETURNING id INTO row_id;
            keep_pat_ids := array_append(keep_pat_ids, row_id);
        END IF;
    END LOOP;
    -- Delete removed patents
    DELETE FROM public.app_patents
    WHERE application_id = p_application_id AND NOT (id = ANY(keep_pat_ids));

    -- 4. Upsert Consultancy
    FOR con_row IN SELECT * FROM jsonb_array_elements(p_consultancy) LOOP
        row_id := (con_row->>'id')::BIGINT;
        IF row_id IS NOT NULL AND row_id > 0 THEN
            UPDATE public.app_consultancy SET
                client_organisation = con_row->>'client_organisation',
                title = con_row->>'title',
                year = NULLIF(con_row->>'year', '')::INTEGER,
                amount = NULLIF(con_row->>'amount', '')::NUMERIC,
                description = con_row->>'description',
                additional_details = con_row->>'additional_details'
            WHERE id = row_id AND application_id = p_application_id;
            keep_con_ids := array_append(keep_con_ids, row_id);
        ELSE
            INSERT INTO public.app_consultancy (
                application_id, client_organisation, title, year, amount, description, additional_details
            ) VALUES (
                p_application_id,
                con_row->>'client_organisation',
                con_row->>'title',
                NULLIF(con_row->>'year', '')::INTEGER,
                NULLIF(con_row->>'amount', '')::NUMERIC,
                con_row->>'description',
                con_row->>'additional_details'
            ) RETURNING id INTO row_id;
            keep_con_ids := array_append(keep_con_ids, row_id);
        END IF;
    END LOOP;
    -- Delete removed consultancy
    DELETE FROM public.app_consultancy
    WHERE application_id = p_application_id AND NOT (id = ANY(keep_con_ids));

    -- 5. Upsert Projects
    FOR prj_row IN SELECT * FROM jsonb_array_elements(p_projects) LOOP
        row_id := (prj_row->>'id')::BIGINT;
        IF row_id IS NOT NULL AND row_id > 0 THEN
            UPDATE public.app_projects SET
                title = prj_row->>'title',
                funding_agency = prj_row->>'funding_agency',
                type = prj_row->>'type',
                amount = NULLIF(prj_row->>'amount', '')::NUMERIC,
                year = NULLIF(prj_row->>'year', '')::INTEGER,
                role = prj_row->>'role',
                additional_details = prj_row->>'additional_details'
            WHERE id = row_id AND application_id = p_application_id;
            keep_prj_ids := array_append(keep_prj_ids, row_id);
        ELSE
            INSERT INTO public.app_projects (
                application_id, title, funding_agency, type, amount, year, role, additional_details
            ) VALUES (
                p_application_id,
                prj_row->>'title',
                prj_row->>'funding_agency',
                prj_row->>'type',
                NULLIF(prj_row->>'amount', '')::NUMERIC,
                NULLIF(prj_row->>'year', '')::INTEGER,
                prj_row->>'role',
                prj_row->>'additional_details'
            ) RETURNING id INTO row_id;
            keep_prj_ids := array_append(keep_prj_ids, row_id);
        END IF;
    END LOOP;
    -- Delete removed projects
    DELETE FROM public.app_projects
    WHERE application_id = p_application_id AND NOT (id = ANY(keep_prj_ids));

END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

REVOKE ALL ON FUNCTION public.save_application_research(BIGINT, JSONB, JSONB, JSONB, JSONB, BOOLEAN, TEXT, TEXT, JSONB) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.save_application_research(BIGINT, JSONB, JSONB, JSONB, JSONB, BOOLEAN, TEXT, TEXT, JSONB) TO service_role;



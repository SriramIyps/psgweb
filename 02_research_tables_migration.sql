-- 1a. Publications Table
CREATE TABLE IF NOT EXISTS public.app_publications (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      BIGINT NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
    type                TEXT NOT NULL CHECK (type IN ('Journal article', 'Book', 'Book chapter')),
    scope               TEXT NOT NULL CHECK (scope IN ('National', 'International')),
    indexing_category   TEXT CHECK (indexing_category IN ('SCI', 'Scopus', 'UGC-listed', 'Other')),
    title               TEXT NOT NULL,
    publisher_journal   TEXT,
    isbn_issn           TEXT,
    year                INTEGER CHECK (year IS NULL OR (year >= 1950 AND year <= 2030)),
    doi_link            TEXT,
    additional_details  TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT check_journal_indexing CHECK (type <> 'Journal article' OR indexing_category IS NOT NULL)
);

-- 1b. Patents Table
CREATE TABLE IF NOT EXISTS public.app_patents (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      BIGINT NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
    title               TEXT NOT NULL,
    status              TEXT NOT NULL CHECK (status IN ('Published', 'Granted')),
    patent_number       TEXT,
    year                INTEGER CHECK (year IS NULL OR (year >= 1950 AND year <= 2030)),
    additional_details  TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW()
);

-- 1c. Consultancy Table
CREATE TABLE IF NOT EXISTS public.app_consultancy (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      BIGINT NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
    client_organisation TEXT NOT NULL,
    title               TEXT NOT NULL,
    year                INTEGER CHECK (year IS NULL OR (year >= 1950 AND year <= 2030)),
    amount              NUMERIC(12,2) CHECK (amount IS NULL OR amount >= 0),
    description         TEXT,
    additional_details  TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW()
);

-- 1d. Projects Table
CREATE TABLE IF NOT EXISTS public.app_projects (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      BIGINT NOT NULL REFERENCES public.applications(id) ON DELETE CASCADE,
    title               TEXT NOT NULL,
    funding_agency      TEXT NOT NULL,
    type                TEXT NOT NULL CHECK (type IN ('Major', 'Minor')),
    amount              NUMERIC(12,2) CHECK (amount IS NULL OR amount >= 0),
    year                INTEGER CHECK (year IS NULL OR (year >= 1950 AND year <= 2030)),
    role                TEXT CHECK (role IN ('PI', 'Co-PI', 'Member')),
    additional_details  TEXT,
    created_at          TIMESTAMPTZ DEFAULT NOW()
);


-- 4. ATOMIC APPLICATION NUMBER GENERATOR RPC
CREATE OR REPLACE FUNCTION public.generate_application_number(p_department TEXT)
RETURNS TEXT AS $$
DECLARE
    dept_code TEXT;
    next_val INTEGER;
    app_num TEXT;
BEGIN
    -- Determine department code prefix
    IF LOWER(p_department) LIKE '%computer%' OR LOWER(p_department) LIKE '%cs%' THEN
        dept_code := 'Comp';
    ELSIF LOWER(p_department) LIKE '%business%' OR LOWER(p_department) LIKE '%bba%' THEN
        dept_code := 'BBA';
    ELSIF LOWER(p_department) LIKE '%math%' THEN
        dept_code := 'Math';
    ELSIF LOWER(p_department) LIKE '%eng%' THEN
        dept_code := 'Eng';
    ELSIF LOWER(p_department) LIKE '%biotech%' THEN
        dept_code := 'BioTech';
    ELSE
        dept_code := UPPER(SUBSTRING(REGEXP_REPLACE(p_department, '[^a-zA-Z]', '', 'g') FROM 1 FOR 4));
        IF LENGTH(dept_code) < 3 THEN
            dept_code := 'GEN';
        END IF;
    END IF;

    -- Atomic counter increment with row lock
    INSERT INTO public.department_counters (department_code, last_number)
    VALUES (dept_code, 1)
    ON CONFLICT (department_code) DO UPDATE
    SET last_number = public.department_counters.last_number + 1
    RETURNING last_number INTO next_val;

    app_num := dept_code || '/' || LPAD(next_val::text, 3, '0');
    RETURN app_num;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

REVOKE ALL ON FUNCTION public.generate_application_number(TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.generate_application_number(TEXT) TO service_role;

-- 5. ATOMIC AUDITED UPDATE RPCs

-- LOCK RPC
CREATE OR REPLACE FUNCTION public.rpc_update_application_lock(
    p_app_id BIGINT,
    p_who TEXT,
    p_is_locked BOOLEAN
) RETURNS VOID AS $$
DECLARE
    v_old_locked BOOLEAN;
BEGIN
    SELECT is_locked INTO v_old_locked FROM public.applications WHERE id = p_app_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'CONNECT_RULE: Application with ID % not found', p_app_id;
    END IF;

    UPDATE public.applications SET is_locked = p_is_locked WHERE id = p_app_id;

    INSERT INTO public.audit_log (who, action, application_id, old_value, new_value, when_timestamp)
    VALUES (p_who, 'ADMIN_UPDATE_IS_LOCKED', p_app_id, v_old_locked::text, p_is_locked::text, NOW());
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

REVOKE ALL ON FUNCTION public.rpc_update_application_lock(BIGINT, TEXT, BOOLEAN) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.rpc_update_application_lock(BIGINT, TEXT, BOOLEAN) TO service_role;


-- 1. AUDIT LOG TABLE
CREATE TABLE IF NOT EXISTS public.audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    who TEXT NOT NULL,
    action TEXT NOT NULL,
    application_id BIGINT REFERENCES public.applications(id) ON DELETE SET NULL,
    old_value TEXT,
    new_value TEXT,
    when_timestamp TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_audit_log_app_id ON public.audit_log(application_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_who ON public.audit_log(who);

-- Enable RLS for Audit Log (No policies for anon or authenticated; strictly service_role)
ALTER TABLE public.audit_log ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admin view audit log" ON public.audit_log;
REVOKE ALL ON public.audit_log FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.audit_log TO service_role;

